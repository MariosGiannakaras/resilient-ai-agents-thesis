def _reader_markdown(md: str, mode: str) -> str:
    if mode == "front":
        return FRONT_READER
    if mode != "main":
        return md
    if re.search(r"^#\s+Κεφάλαιο 1\b", md, re.MULTILINE):
        return CH1_READER
    if re.search(r"^#\s+Κεφάλαιο 2\b", md, re.MULTILINE):
        marker = "## 2.7"
        if marker not in md:
            raise RuntimeError("T-715 could not locate Chapter 2 compression boundary")
        return md.split(marker, 1)[0].rstrip() + "\n\n" + CH2_TAIL
    if re.search(r"^#\s+Κεφάλαιο 3\b", md, re.MULTILINE):
        return CH3_READER
    if re.search(r"^#\s+Κεφάλαιο 4\b", md, re.MULTILINE):
        return CH4_READER
    if re.search(r"^#\s+Κεφάλαιο 5\b", md, re.MULTILINE):
        return CH5_READER
    if re.search(r"^#\s+Κεφάλαιο 6\b", md, re.MULTILINE):
        return CH6_READER
    if re.search(r"^#\s+Κεφάλαιο 7\b", md, re.MULTILINE):
        return CH7_READER
    return md



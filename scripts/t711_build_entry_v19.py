def _toc_cache_lines() -> list[str]:
    lines: list[str] = []
    sources = [
        *((path, "main") for path in t711.builder.MANUSCRIPT_FILES),
        (t711.builder.GLOSSARY_FILE, "glossary"),
        (t711.builder.APPENDIX_FILE, "appendix"),
    ]
    for path, mode in sources:
        cleaned = _reader_preprocess(path.read_text(encoding="utf-8"), mode)
        for raw in cleaned.splitlines():
            match = re.match(r"^(#{1,3})\s+(.+)$", raw.strip())
            if not match:
                continue
            title = t711.builder.strip_markdown_inline(match.group(2))
            if "T-711 appendix assembly rules" in title:
                continue
            lines.append("    " * (len(match.group(1)) - 1) + title)
    lines.append("Βιβλιογραφία")
    return lines


def _main_text(doc: Document) -> str:
    values: list[str] = []
    in_main = False
    for paragraph in doc.paragraphs:
        if paragraph.text.startswith("Κεφάλαιο 1"):
            in_main = True
        if paragraph.text == "Γλωσσάριο και Ακρωνύμια" or paragraph.text.startswith("Παράρτημα Α"):
            in_main = False
        if in_main:
            values.append(paragraph.text)
    return "\n".join(values)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _build(output: Path, qa_output: Path) -> None:
    _previous_build(output, qa_output)
    report = json.loads(qa_output.read_text(encoding="utf-8"))
    doc = Document(output)
    main_text = _main_text(doc)
    lower = main_text.lower()

    forbidden = sorted(
        phrase for phrase in (
            "studystore",
            "deterministic job plan",
            "actual-environment-interaction fairness boundary",
            "sha-256",
            "artifact registrations",
            "p-value superiority family",
        )
        if phrase in lower
    )

    # The main Word body deliberately uses nine registered figures; all other registered
    # scientific figures remain in the appendix. The synthesis graphic remains unnumbered.
    report.update(
        {
            "output_sha256": _sha256(output),
            "paragraph_count": len(doc.paragraphs),
            "post_synthesis_paragraph_count": len(doc.paragraphs),
            "t715_reader_scope_simplification": True,
            "t715_detailed_scientific_source_preserved": True,
            "t715_main_registered_figure_count": len(MAIN_FIGURE_IDS),
            "t715_appendix_registered_figure_count": len(APPENDIX_FIGURE_IDS),
            "t715_total_registered_figure_count": len(PLANNED_FIGURE_IDS),
            "t715_main_forbidden_internal_detail": forbidden,
            "t715_main_character_count": len(main_text),
            "t715_main_word_count_approx": len(re.findall(r"\S+", main_text)),
            "t715_secondary_diagnostics_moved_to_appendix": [
                "FIG-RQ2-010-CONDITIONS",
                "FIG-RQ3-019-CONDITIONAL",
                "FIG-RQ3-023-SENSITIVITY",
            ],
            "scientific_values_modified": False,
            "registered_asset_bytes_modified": False,
            "final_visual_qa_required": True,
        }
    )
    if (
        forbidden
        or len(PLANNED_FIGURE_IDS) != 24
        or set(MAIN_FIGURE_IDS) & set(APPENDIX_FIGURE_IDS)
        or set(MAIN_FIGURE_IDS) | set(APPENDIX_FIGURE_IDS) != set(v5.PLANNED_FIGURE_IDS)
    ):
        report["status"] = "fail"

    qa_output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if report.get("status") != "pass":
        raise RuntimeError(f"T-715 reader-scope QA failed: {report}")


